-- Run AFTER the CSV files in /data have been imported.
-- Normalizes ADDRESSES into lookup tables and adds a card-number constraint.

CREATE TABLE COUNTRIES (
    Country VARCHAR(50) PRIMARY KEY
);

CREATE TABLE CITIES (
    City VARCHAR(50) PRIMARY KEY
);

CREATE TABLE STREETS (
    Street VARCHAR(100) PRIMARY KEY
);

INSERT INTO COUNTRIES (Country)
SELECT DISTINCT Country
FROM ADDRESSES;

INSERT INTO CITIES (City)
SELECT DISTINCT City
FROM ADDRESSES;

INSERT INTO STREETS (Street)
SELECT DISTINCT Street
FROM ADDRESSES;

ALTER TABLE ADDRESSES
ADD FOREIGN KEY (Country) REFERENCES COUNTRIES(Country);

ALTER TABLE ADDRESSES
ADD FOREIGN KEY (City) REFERENCES CITIES(City);

ALTER TABLE ADDRESSES
ADD FOREIGN KEY (Street) REFERENCES STREETS(Street);

ALTER TABLE PAYMENTS
ADD CONSTRAINT CHK_Payments_CardNumber
CHECK (
    LEN(CardNumber) = 16
    AND CardNumber NOT LIKE '%[^0-9]%'
);
